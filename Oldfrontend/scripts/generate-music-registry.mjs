import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const frontendRoot = path.resolve(__dirname, '..');
const repoRoot = path.resolve(frontendRoot, '..');
const musicDir = path.join(frontendRoot, 'public', 'music');
const frontendOutput = path.join(
  frontendRoot,
  'src',
  'Pages',
  'Dashboard',
  'component',
  'SystemIdleGame',
  'audio',
  'generatedMusicRegistry.ts',
);
const backendOutput = path.join(
  repoRoot,
  'backend',
  'storylineCore',
  'catalogs',
  'generatedMusicAudioManifest.js',
);

const supportedExtensions = new Set(['.mp3', '.wav', '.ogg', '.m4a']);
const overrides = {
  '1-03. Subwoofer Lullaby.mp3': {
    id: 'music.subwoofer_lullaby',
    label: 'Subwoofer Lullaby',
  },
  'Travelers.mp3': {
    id: 'music.travelers',
    label: 'Travelers',
  },
};

function musicFiles() {
  if (!fs.existsSync(musicDir)) return [];
  return collectMusicFiles(musicDir)
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }));
}

function collectMusicFiles(directory) {
  const files = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...collectMusicFiles(fullPath));
      continue;
    }
    if (!entry.isFile() || !supportedExtensions.has(path.extname(entry.name).toLowerCase())) continue;
    files.push(path.relative(musicDir, fullPath).split(path.sep).join('/'));
  }
  return files;
}

function trackFromFile(relativePath) {
  const fileName = path.posix.basename(relativePath);
  const fallbackLabel = path.posix.basename(fileName, path.posix.extname(fileName))
    .replace(/^\d+(?:-\d+)?[.\s_-]+/, '')
    .replace(/[_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  const override = overrides[relativePath] ?? overrides[fileName];
  const label = override?.label || titleCase(fallbackLabel || fileName);
  const fallbackIdSource = relativePath.includes('/')
    ? relativePath.slice(0, -path.posix.extname(relativePath).length)
    : label;
  const id = override?.id || `music.${slug(fallbackIdSource)}`;
  return {
    id,
    label,
    channel: 'music',
    source: { kind: 'relative', path: `/music/${encodeMusicPath(relativePath)}` },
    preload: true,
    loop: false,
    volume: 0.62,
    tags: ['music', 'playlist'],
    notes: 'Generated playlist track from frontend/public/music.',
  };
}

function encodeMusicPath(relativePath) {
  return relativePath
    .split('/')
    .map((segment) => encodeURIComponent(segment).replace(/'/g, '%27'))
    .join('/');
}

function slug(value) {
  const normalized = value
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/['’]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');
  return normalized || 'track';
}

function titleCase(value) {
  return value.replace(/(^|[\s_-])([a-z])/g, (_match, prefix, letter) => `${prefix}${letter.toUpperCase()}`);
}

function writeIfChanged(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  if (fs.existsSync(filePath) && fs.readFileSync(filePath, 'utf8') === content) return;
  fs.writeFileSync(filePath, content, 'utf8');
}

const tracks = musicFiles().map(trackFromFile);
const frontendContent = `// Generated by frontend/scripts/generate-music-registry.mjs. Do not edit by hand.
import type { AudioRegistryEntry } from './AudioTypes';

export const GENERATED_MUSIC_DIRECTORY_TRACKS: AudioRegistryEntry[] = ${JSON.stringify(tracks, null, 2)};
`;
const manifest = tracks.map(({ id, channel, label }) => ({ id, channel, label }));
const backendContent = `// Generated by frontend/scripts/generate-music-registry.mjs. Do not edit by hand.
const GENERATED_MUSIC_AUDIO_MANIFEST = ${JSON.stringify(manifest, null, 2)};

module.exports = {
  GENERATED_MUSIC_AUDIO_MANIFEST,
};
`;

writeIfChanged(frontendOutput, frontendContent);
writeIfChanged(backendOutput, backendContent);
console.log(`Generated ${tracks.length} music track${tracks.length === 1 ? '' : 's'}.`);
