import type { MaterialCost } from "../../logic/buildings.js";

/**
 * 领地扩展的调参。
 *
 * ## 为什么价钱在 Core 不在面板里
 *
 * 和建筑造价同一条纪律：**内容规则只有一份**（AGENTS.md——Backend 不得
 * 复制一份独立的），联机时服务端要用同一个数校验"这块地你买得起吗"。
 * 写死在 BuildShopPanel 里的话，服务端要么信客户端，要么自己抄一遍。
 *
 * ## 为什么是一个数不是每块地一个价
 *
 * 今天八块地同价（用户 2026-08-23 定：50 金币）。**没做成
 * `PlotDefinition.unlockCost`** 是因为那会逼着八块地各写一遍同一个数，
 * 而"这块地为什么比那块贵"目前没有答案——等真有了（越远越贵、
 * 好地段溢价），字段加在 PlotDefinition 上、这里退化成缺省值。
 */
export const territoryTuning = {
  /**
   * 开一块地要多少。**50 金币**。
   *
   * 这个数是**卡在罐子上的**，不是卡在收入上：钱匣只装 10，l1 罐也只装
   * 10，两者加起来 20 —— 也就是说光靠打勾攒钱永远够不到 50，
   * 必须先把罐升到 l2（容量 150）。扩地因此天然排在"建罐 → 升罐"之后，
   * 不用另写一条前置条件。
   *
   * 每日任务一天满打满算 32 金币（4 个勾 × 5 + 满格 12），所以升完罐
   * 之后大约**两天**能开一块地。
   */
  unlockCost: [{ itemId: "gold", quantity: 50 }] as MaterialCost,
};
